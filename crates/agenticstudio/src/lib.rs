//! agenticstudio: drafts of agenticspec architectures, changed by patches (`agenticspec-patch/1`)
//! and shown in the browser by the app `ui/studio` generated from `studio/studio.ui.yaml`.
//!
//! - `studio`: the drafts, their revisions, patches and patch applications, the sessions on them
//!   and their tool calls, held in memory.
//! - `tools`: the four tools of a session (query, apply, check, simulate) and their answers.
//! - `live`: the event channel of each draft, and its server-sent-events stream.
//! - `routes`: the HTTP routes over them, answered without a socket.
//! - `http`: reading a request from and writing a response to a connection.
//! - `app`: the views and commands the generated app (`ui/studio`) calls, and its built files.
//! - `types`: the types of the drafts (`studio/`) and of the architecture block
//!   (`blocks/9-composition/architecture.yaml`), generated by `ess generate types`.

pub mod app;
pub mod http;
pub mod live;
pub mod routes;
pub mod studio;
pub mod tools;

#[doc(hidden)]
#[rustfmt::skip]
#[allow(dead_code, clippy::all, clippy::pedantic)]
#[path = "generated/studio/types.rs"]
pub mod generated_studio;
#[doc(hidden)]
#[rustfmt::skip]
#[allow(dead_code, clippy::all, clippy::pedantic)]
#[path = "generated/session/types.rs"]
pub mod generated_session;
#[doc(hidden)]
#[rustfmt::skip]
#[allow(dead_code, clippy::all, clippy::pedantic)]
#[path = "generated/architecture/types.rs"]
pub mod generated_architecture;

/// The generated types. Never edited: `task generate` writes them, `task check:generated`
/// compares them byte for byte. `studio` is from `studio/` (the draft), `session` from `studio/`
/// (sessions, tool calls and the revision event); `architecture` from the
/// architecture block (revisions, patches and patch applications).
pub mod types {
    pub use super::generated_architecture as architecture;
    pub use super::generated_session as session;
    pub use super::generated_studio as studio;
}
