//! The catalog of pre-built, optimized architectures: one entry per experiment, run with its own
//! budget and seeds, with its full result page, the best variant as an architecture document and
//! the files to download and run it; an index of cards; the architectures no experiment searches.

use crate::SOURCE_BASE;
use crate::cache;
use crate::md::{attr, code, first_sentence, text, yaml};
use agenticspec_sim::best::{fitness_as_written, yaml_of_result};
use agenticspec_sim::doc::parse_yaml;
use agenticspec_sim::{Experiment, run};
use serde_json::{Value, json};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The note at the top of every generated catalog page.
const NOTE: &str = "{/* Generated by agenticspec-docs from experiments/, architectures/ and profiles/. Do not edit. */}\n\n";

/// The stage of the agentic ladder an architecture plainly belongs to; an architecture not listed
/// gets no stage.
const STAGES: &[(&str, &str)] = &[
    ("orchestrator-workers", "S2"),
    ("workstation", "S2"),
    ("scheduled-loops", "S3"),
];

pub struct Entry {
    /// The architecture's file name without `.yaml`; the entry's route and directory.
    pub name: String,
    pub arch_text: String,
    pub doc: Value,
    pub exp_file: String,
    pub exp_name: String,
    pub exp_text: String,
    pub profile_name: String,
    pub profile_text: String,
    pub seeds: u64,
    pub weights: BTreeMap<String, f64>,
    pub result: Value,
    /// The best variant as an architecture document, when a variant passed the gates.
    pub best: Option<String>,
}

/// An architecture without an experiment.
pub struct Unsearched {
    pub name: String,
    pub summary: String,
}

pub struct Catalog {
    pub entries: Vec<Entry>,
    pub unsearched: Vec<Unsearched>,
    /// The ladder's stages, id to name, when the site has the ladder page.
    pub stages: BTreeMap<String, String>,
}

fn yaml_files(dir: &Path) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "yaml" || x == "yml"))
        .collect();
    out.sort();
    out
}

fn stem(p: &Path) -> String {
    p.file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default()
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

/// The experiment's text with `architecture:` and `profile:` pointing at the files beside it, as
/// they are downloaded into one directory.
fn local_experiment(text: &str, arch: &str, profile: &str) -> Result<String, String> {
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let end = if line.ends_with('\n') { "\n" } else { "" };
        if line.starts_with("architecture:") {
            let _ = write!(out, "architecture: {arch}{end}");
        } else if line.starts_with("profile:") {
            let _ = write!(out, "profile: {profile}{end}");
        } else {
            out.push_str(line);
        }
    }
    let doc = parse_yaml(&out)?;
    if doc["architecture"] != arch || doc["profile"] != profile {
        return Err("its architecture and profile are not one line each".into());
    }
    Ok(out)
}

fn ladder_stages(root: &Path) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    if !root.join("docs/ladder.mdx").exists() {
        return out;
    }
    let Ok(doc) = agenticspec_sim::doc::load_yaml(&root.join("ladder/ladder.yaml")) else {
        return out;
    };
    for s in doc["stages"].as_array().into_iter().flatten() {
        if let (Some(id), Some(name)) = (s["id"].as_str(), s["name"].as_str()) {
            out.insert(id.to_string(), name.to_string());
        }
    }
    out
}

/// Runs every experiment under `experiments/` as configured and collects the catalog.
pub fn load(root: &Path) -> Result<Catalog, String> {
    let threads = std::thread::available_parallelism().map_or(1, |n| n.get().min(8));
    let mut entries: Vec<Entry> = Vec::new();
    let mut searched = BTreeSet::new();
    for ep in yaml_files(&root.join("experiments")) {
        let exp_file = format!(
            "experiments/{}",
            ep.file_name().unwrap_or_default().to_string_lossy()
        );
        let exp_text = read(&ep)?;
        let edoc = parse_yaml(&exp_text).map_err(|e| format!("{exp_file}: {e}"))?;
        let dir = ep.parent().unwrap_or(Path::new("."));
        let arch_path = dir.join(
            edoc["architecture"]
                .as_str()
                .ok_or(format!("{exp_file}: needs `architecture`"))?,
        );
        let profile_path = dir.join(
            edoc["profile"]
                .as_str()
                .ok_or(format!("{exp_file}: needs `profile`"))?,
        );
        let e = Experiment::load(&ep).map_err(|err| format!("{exp_file}: {err}"))?;
        let arch_text = read(&arch_path)?;
        let profile_text = read(&profile_path)?;
        let key = cache::key(&[&exp_text, &arch_text, &profile_text]);
        let result = cache::get_or(&key, || {
            let result = run(&e, threads)?;
            // The downloaded optimized architecture must give the best fitness under the experiment.
            if let Some(text) = yaml_of_result(&result, Some(&arch_text))? {
                let want = result["best"]["fitness"].as_f64().unwrap_or(f64::NAN);
                let got = fitness_as_written(&e, parse_yaml(&text)?, threads)?;
                if got != want {
                    return Err(format!(
                        "its best variant written as an architecture scores {got}, not {want}"
                    ));
                }
            }
            Ok(result)
        })
        .map_err(|err| format!("{exp_file}: {err}"))?;
        let best = yaml_of_result(&result, Some(&arch_text))
            .map_err(|err| format!("{exp_file}: {err}"))?;
        let mut name = stem(&arch_path);
        if entries.iter().any(|x| x.name == name) {
            name = stem(&ep);
        }
        searched.insert(stem(&arch_path));
        entries.push(Entry {
            arch_text,
            doc: e.architecture.clone(),
            exp_name: edoc["experiment"]
                .as_str()
                .unwrap_or(&stem(&ep))
                .to_string(),
            exp_file,
            exp_text,
            profile_name: stem(&profile_path),
            profile_text,
            seeds: e.seeds,
            weights: e.search.weights.clone(),
            result,
            best,
            name,
        });
    }
    let mut unsearched = Vec::new();
    for path in yaml_files(&root.join("architectures")) {
        let name = stem(&path);
        if searched.contains(&name) {
            continue;
        }
        let doc = agenticspec_sim::doc::load_yaml(&path)?;
        unsearched.push(Unsearched {
            name,
            summary: doc["summary"].as_str().unwrap_or("").to_string(),
        });
    }
    Ok(Catalog {
        entries,
        unsearched,
        stages: ladder_stages(root),
    })
}

/// A figure for a reader: whole numbers as such, else 1 to 3 decimals by size.
fn num(x: f64) -> String {
    if x.fract() == 0.0 && x.abs() < 1e12 {
        format!("{}", x as i64)
    } else if x.abs() >= 100.0 {
        format!("{x:.1}")
    } else if x.abs() >= 1.0 {
        format!("{x:.2}")
    } else {
        format!("{x:.3}")
    }
}

fn signed(x: f64) -> String {
    if x >= 0.0 {
        format!("+{}", num(x))
    } else {
        format!("−{}", num(-x))
    }
}

/// A value of a marked place as written: `15m`, `12`, `parallel`.
fn place_value(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// How a weighted KPI moved from the architecture as written to the best variant.
struct Move {
    kpi: String,
    from: f64,
    to: f64,
    /// Its change of the fitness: weight times the change of the KPI.
    contribution: f64,
}

fn moves(e: &Entry) -> Vec<Move> {
    let base = &e.result["baseline"]["kpis"];
    let best = &e.result["best"]["kpis"];
    let mut out: Vec<Move> = e
        .weights
        .iter()
        .filter_map(|(k, w)| {
            let from = base[k]["value"].as_f64()?;
            let to = best[k]["value"].as_f64()?;
            let contribution = w * (to - from);
            (contribution.abs() > 1e-9).then(|| Move {
                kpi: k.clone(),
                from,
                to,
                contribution,
            })
        })
        .collect();
    out.sort_by(|a, b| {
        b.contribution
            .abs()
            .total_cmp(&a.contribution.abs())
            .then(a.kpi.cmp(&b.kpi))
    });
    out
}

fn fitness(e: &Entry) -> (f64, Option<f64>) {
    (
        e.result["baseline"]["fitness"].as_f64().unwrap_or(0.0),
        e.result["best"]["fitness"].as_f64(),
    )
}

/// The gain of the fitness: `+1.6 %`, or the difference when the baseline is not above 0.
fn gain(base: f64, best: f64) -> String {
    if base > 0.0 {
        let pct = (best - base) / base * 100.0;
        format!("{}{:.1} %", if pct >= 0.0 { "+" } else { "−" }, pct.abs())
    } else {
        signed(best - base)
    }
}

/// `232.2 → 235.9 (+1.6 %)`.
fn headline(base: f64, best: f64) -> String {
    format!("{} → {} ({})", num(base), num(best), gain(base, best))
}

/// A weight as the experiment writes it, with its sign: `+10`, `−0.05`.
fn weight(w: f64) -> String {
    format!("{}{}", if w < 0.0 { "−" } else { "+" }, w.abs())
}

fn move_json(m: &Move) -> Value {
    json!({
        "kpi": m.kpi,
        "from": num(m.from),
        "to": num(m.to),
        "contribution": signed(m.contribution),
    })
}

fn card(e: &Entry, stages: &BTreeMap<String, String>) -> Value {
    let (base, best) = fitness(e);
    let all = moves(e);
    let gains: Vec<Value> = all
        .iter()
        .filter(|m| m.contribution > 0.0)
        .take(2)
        .map(move_json)
        .collect();
    let tradeoff = all
        .iter()
        .filter(|m| m.contribution < 0.0)
        .max_by(|a, b| (-a.contribution).total_cmp(&-b.contribution))
        .map(move_json);
    let stage = STAGES
        .iter()
        .find(|(n, _)| *n == e.name)
        .and_then(|(_, id)| stages.get(*id).map(|name| json!({"id": id, "name": name})));
    json!({
        "name": e.name,
        "to": format!("/docs/catalog/{}", e.name),
        "purpose": first_sentence(e.doc["summary"].as_str().unwrap_or("")).replace('`', ""),
        "experiment": e.exp_name,
        "variants": e.result["variants"].as_array().map_or(0, Vec::len),
        "seeds": e.seeds,
        "fitness": best.map(|b| json!({"from": num(base), "to": num(b), "gain": gain(base, b)})),
        "gains": gains,
        "tradeoff": tradeoff,
        "stage": stage,
    })
}

/// The files of an entry under `website/static/catalog/<name>/`, by path relative to the root.
pub fn files(e: &Entry) -> Result<BTreeMap<String, String>, String> {
    let dir = format!("website/static/catalog/{}", e.name);
    let mut out = BTreeMap::new();
    out.insert(
        format!("{dir}/{}.html", e.name),
        agenticspec_render::page(&e.result["architecture"], Some(&e.result)),
    );
    out.insert(format!("{dir}/{}.yaml", e.name), e.arch_text.clone());
    if let Some(best) = &e.best {
        out.insert(format!("{dir}/{}.best.yaml", e.name), best.clone());
    }
    out.insert(
        format!("{dir}/{}.yaml", e.exp_name),
        local_experiment(
            &e.exp_text,
            &format!("{}.yaml", e.name),
            &format!("{}.yaml", e.profile_name),
        )
        .map_err(|err| format!("{}: {err}", e.exp_file))?,
    );
    out.insert(
        format!("{dir}/{}.yaml", e.profile_name),
        e.profile_text.clone(),
    );
    let mut json = serde_json::to_string_pretty(&e.result).map_err(|err| err.to_string())?;
    json.push('\n');
    out.insert(format!("{dir}/result.json"), json);
    Ok(out)
}

#[allow(clippy::too_many_arguments)]
fn front(
    s: &mut String,
    title: &str,
    label: &str,
    slug: &str,
    lede: &str,
    source: &str,
    url: &str,
    component: &str,
) {
    s.push_str("---\n");
    let _ = writeln!(s, "title: {}", yaml(title));
    let _ = writeln!(s, "sidebar_label: {}", yaml(label));
    let _ = writeln!(s, "slug: {slug}");
    let _ = writeln!(s, "description: {}", yaml(lede));
    let _ = writeln!(s, "lede: {}", yaml(lede));
    let _ = writeln!(s, "kicker: {}", yaml("Catalog"));
    let _ = writeln!(s, "source: {}", yaml(source));
    let _ = writeln!(s, "source_url: {}", yaml(url));
    s.push_str("mdx:\n  format: mdx\n---\n\n");
    s.push_str(NOTE);
    let _ = writeln!(
        s,
        "import {component} from '@site/src/components/catalog/{component}';\n"
    );
}

/// The page of one entry.
pub fn page(e: &Entry) -> String {
    let summary = e.doc["summary"].as_str().unwrap_or("");
    let lede = first_sentence(summary);
    let mut s = String::new();
    front(
        &mut s,
        &e.name,
        &e.name,
        &format!("/catalog/{}", e.name),
        &lede,
        &e.exp_file,
        &format!("{SOURCE_BASE}{}", e.exp_file),
        "CatalogDownloads",
    );
    let (base, best) = fitness(e);
    let variants = e.result["variants"].as_array().map_or(0, Vec::len);
    let horizon = e.result["experiment"]["horizon"].as_str().unwrap_or("24h");
    let _ = writeln!(
        s,
        "The architecture [{}](../architectures/{}.md), optimized by the experiment [{}]({SOURCE_BASE}{}): \
{variants} variants of its marked places, each simulated for {} with {} seed{} under the behaviour profile {}.\n",
        e.name,
        e.name,
        text(&e.exp_name),
        e.exp_file,
        text(horizon),
        e.seeds,
        if e.seeds == 1 { "" } else { "s" },
        code(&e.profile_name)
    );
    match best {
        Some(b) => {
            let _ = writeln!(
                s,
                "**Fitness {}**, as written → optimized. Fitness is the weighted sum of the KPIs the experiment scores.\n",
                headline(base, b)
            );
        }
        None => s.push_str("No variant passed the experiment's gates, so there is no optimized architecture yet.\n\n"),
    }

    if let Some(params) = e.result["best"]["params"].as_object() {
        s.push_str("## What the optimization changed\n\n");
        let marked = e.result["marked"].as_array().cloned().unwrap_or_default();
        let changed: Vec<(String, String, String)> = marked
            .iter()
            .filter_map(|m| {
                let path = m["path"].as_str()?;
                let from = place_value(&m["value"]);
                let to = place_value(params.get(path)?);
                (from != to).then(|| (path.to_string(), from, to))
            })
            .collect();
        if changed.is_empty() {
            let _ = writeln!(
                s,
                "Nothing: of {} marked places, the values as written are the best variant the search found.\n",
                marked.len()
            );
        } else {
            let _ = writeln!(
                s,
                "{} of {} marked places {} another value; the others keep theirs.\n",
                changed.len(),
                marked.len(),
                if changed.len() == 1 { "takes" } else { "take" },
            );
            s.push_str("| marked place | as written | optimized |\n|---|---|---|\n");
            for (path, from, to) in changed {
                let _ = writeln!(
                    s,
                    "| {} | {} | **{}** |",
                    code(&path),
                    text(&from),
                    text(&to)
                );
            }
            s.push('\n');
        }
        let all = moves(e);
        if !all.is_empty() {
            s.push_str(
                "The weighted KPIs that moved, the largest change of the fitness first:\n\n",
            );
            s.push_str(
                "| KPI | weight | as written | optimized | fitness |\n|---|---|---|---|---|\n",
            );
            for m in &all {
                let w = e.weights.get(&m.kpi).copied().unwrap_or(0.0);
                let _ = writeln!(
                    s,
                    "| {} | {} | {} | {} | {} |",
                    code(&m.kpi),
                    weight(w),
                    num(m.from),
                    num(m.to),
                    signed(m.contribution)
                );
            }
            s.push('\n');
        }
    }

    s.push_str("## Result\n\n");
    let _ = writeln!(
        s,
        "<ArchitectureFrame name={} src={} caption={} />\n",
        attr(&e.name),
        attr(&format!("/catalog/{}/{}", e.name, e.name)),
        attr(&format!(
            "The full result of {}: objective, landscape, trade-offs, sensitivity, variants and timeline.",
            e.exp_name
        ))
    );

    s.push_str("## Download\n\n");
    let mut list = vec![
        json!({"file": format!("{}.yaml", e.name), "label": "Architecture as written", "about": "the parts, links and policies, with the marked places at their values as written"}),
    ];
    if e.best.is_some() {
        list.push(json!({"file": format!("{}.best.yaml", e.name), "label": "Optimized architecture", "about": "every marked place at the value of the best variant; its vary ranges are kept, so it can be searched again"}));
    }
    list.push(json!({"file": format!("{}.yaml", e.exp_name), "label": "Experiment", "about": "seeds, horizon, faults, the search and its weights; it names the two files beside it"}));
    list.push(json!({"file": format!("{}.yaml", e.profile_name), "label": "Behaviour profile", "about": "how long turns, builds and answers take, and what model calls cost"}));
    list.push(json!({"file": "result.json", "label": "Result", "about": "every variant with its KPIs, the best one and the timeline, as the result page draws it"}));
    let _ = writeln!(
        s,
        "<CatalogDownloads dir={} files={{{}}} />\n",
        attr(&format!("/catalog/{}/", e.name)),
        Value::Array(list)
    );

    s.push_str("## Run it\n\n");
    let _ = writeln!(
        s,
        "Put the downloaded files in one directory and run the experiment with `agenticspec-sim`, which a checkout of the \
[repository](https://github.com/beyond10x/agenticspec) builds with `cargo build --release -p agenticspec-sim`. \
The same seeds give the same `result.json`.\n"
    );
    let _ = writeln!(
        s,
        "```sh\nagenticspec-sim run {exp}.yaml --out out/\n```\n",
        exp = e.exp_name
    );
    if e.best.is_some() {
        let _ = writeln!(
            s,
            "`agenticspec-sim check {name}.best.yaml` accepts the optimized architecture. To search on from it, set \
`architecture: {name}.best.yaml` in the experiment; its fitness as written is then the best fitness above.\n",
            name = e.name
        );
    }
    let _ = writeln!(
        s,
        "In a checkout, the same run is `agenticspec-sim run {} --out out/`.\n",
        e.exp_file
    );

    s.push_str("## Deploy\n\n");
    s.push_str(
        "Later. An entry runs in the simulator today; the agent runtime and the compute that implement the building blocks come later, and with them a way to deploy an entry.\n",
    );
    s
}

/// The index page: one card per entry, then the architectures no experiment searches yet.
pub fn index(c: &Catalog) -> String {
    let mut s = String::new();
    front(
        &mut s,
        "Catalog",
        "Overview",
        "/catalog",
        "Pre-built architectures, each optimized by an experiment: the full result of its search, the files to download and the command to run it.",
        "experiments/",
        &format!("{}experiments", SOURCE_BASE.replace("/blob/", "/tree/")),
        "CatalogCards",
    );
    s.push_str(
        "Each entry is an [architecture](../architectures/index.md) an experiment optimized in the simulator. \
**Fitness** is the weighted sum of the KPIs the experiment scores, as written → optimized; a card names the KPIs that gained most and the one that got worse.\n\n",
    );
    s.push_str("## Optimized\n\n");
    let cards: Vec<Value> = c.entries.iter().map(|e| card(e, &c.stages)).collect();
    let _ = writeln!(s, "<CatalogCards entries={{{}}} />\n", Value::Array(cards));
    if !c.unsearched.is_empty() {
        s.push_str("## Not optimized yet\n\n");
        s.push_str("No experiment searches these architectures yet. Each links to its architecture page.\n\n");
        s.push_str("| architecture | what it is for |\n|---|---|\n");
        for u in &c.unsearched {
            let _ = writeln!(
                s,
                "| [{}](../architectures/{}.md) | {} |",
                u.name,
                u.name,
                text(&first_sentence(&u.summary))
            );
        }
        s.push('\n');
    }
    s
}
