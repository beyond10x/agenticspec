//! The layer map and one page per block.

use crate::SOURCE_BASE;
use crate::kpis::{Catalogue, KINDS, Kpi, status_words};
use crate::layout::Map;
use crate::md::{attr, code, condition, first_sentence, predicate, text, type_ref, yaml};
use crate::model::{Block, members, short};
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::fmt::Write as _;

pub struct Ctx<'a> {
    pub ir: &'a Value,
    pub blocks: &'a [Block],
    pub edges: &'a BTreeMap<(String, String), usize>,
    pub catalogue: &'a Catalogue,
    /// Blocks the catalogue names that blocks/ does not declare yet.
    pub planned: &'a [String],
}

impl Ctx<'_> {
    fn block(&self, domain: &str) -> Option<&Block> {
        self.blocks.iter().find(|b| b.domain == domain)
    }

    fn depends_on(&self, b: &Block) -> Vec<(&Block, usize)> {
        let mut out: Vec<(&Block, usize)> = self
            .edges
            .iter()
            .filter(|((f, _), _)| *f == b.domain)
            .filter_map(|((_, t), n)| self.block(t).map(|x| (x, *n)))
            .collect();
        out.sort_by(|a, b| {
            (std::cmp::Reverse(a.0.layer), &a.0.name)
                .cmp(&(std::cmp::Reverse(b.0.layer), &b.0.name))
        });
        out
    }

    fn used_by(&self, b: &Block) -> Vec<(&Block, usize)> {
        let mut out: Vec<(&Block, usize)> = self
            .edges
            .iter()
            .filter(|((_, t), _)| *t == b.domain)
            .filter_map(|((f, _), n)| self.block(f).map(|x| (x, *n)))
            .collect();
        out.sort_by(|a, b| (a.0.layer, &a.0.name).cmp(&(b.0.layer, &b.0.name)));
        out
    }

    fn count(&self, b: &Block, kind: &str) -> usize {
        self.ir["domains"][&b.domain][kind]
            .as_array()
            .map_or(0, |a| a.len())
    }

    fn refusals(&self, b: &Block) -> usize {
        members(self.ir, &b.domain, "commands")
            .iter()
            .flat_map(|c| c["outcomes"].as_array().into_iter().flatten())
            .filter(|o| o["error"].is_string())
            .count()
    }
}

/// A link from the page of `from` to the page of `to`.
fn rel(from: &Block, to: &Block) -> String {
    if from.section != to.section {
        format!("../../{}/{}/{}.md", to.section, to.dir, to.page)
    } else if from.dir == to.dir {
        format!("{}.md", to.page)
    } else {
        format!("../{}/{}.md", to.dir, to.page)
    }
}

pub(crate) fn front(out: &mut String, fields: &[(&str, String)]) {
    out.push_str("---\n");
    for (k, v) in fields {
        let _ = writeln!(out, "{k}: {v}");
    }
    out.push_str("mdx:\n  format: mdx\n---\n\n");
}

pub const GENERATED_NOTE: &str =
    "{/* Generated by agenticspec-docs from the specification in blocks/. Do not edit. */}\n\n";

pub fn index(ctx: &Ctx) -> String {
    let mut s = String::new();
    front(
        &mut s,
        &[
            ("title", yaml("Building blocks")),
            ("sidebar_label", yaml("Layer map")),
            ("slug", "/blocks".into()),
            (
                "description",
                yaml(
                    "Every building block of agentic development, by layer, with the blocks it depends on.",
                ),
            ),
            (
                "lede",
                yaml(
                    "What agentic development is made of: 21 blocks in 11 layers. Each block is a contract of commands, events and views. Dependencies point down only.",
                ),
            ),
            ("source", yaml("blocks/")),
            (
                "source_url",
                yaml(&format!(
                    "{}blocks",
                    SOURCE_BASE.replace("/blob/", "/tree/")
                )),
            ),
            ("hide_table_of_contents", "true".into()),
        ],
    );
    s.push_str(GENERATED_NOTE);
    let entities: usize = ctx.blocks.iter().map(|b| ctx.count(b, "entities")).sum();
    let commands: usize = ctx.blocks.iter().map(|b| ctx.count(b, "commands")).sum();
    let events: usize = ctx.blocks.iter().map(|b| ctx.count(b, "events")).sum();
    let layers = ctx
        .blocks
        .iter()
        .map(|b| b.layer)
        .max()
        .map_or(0, |l| l + 1);
    let _ = writeln!(
        s,
        "The specification declares {} blocks in {layers} layers, with {entities} entities, {commands} commands and {events} events. \
A block uses only blocks of its own layer or a lower one: an arrow points from a block to a block it depends on. \
The foundation, `shared`, holds the identifiers, content and money types every block uses; its arrows are left out.\n",
        ctx.blocks.len()
    );
    s.push_str("<BlockMap />\n\n");
    s.push_str("## Every block\n\n");
    s.push_str("| layer | block | what it is | depends on | KPIs |\n|---|---|---|---|---|\n");
    let mut layer = u32::MAX;
    for b in ctx.blocks.iter().rev() {
        let layer_cell = if b.layer != layer {
            layer = b.layer;
            format!("**{}** {}", b.layer, b.layer_name())
        } else {
            String::new()
        };
        let deps: Vec<String> = ctx
            .depends_on(b)
            .iter()
            .map(|(d, _)| format!("[{}]({}/{}.md)", d.name, d.dir, d.name))
            .collect();
        let _ = writeln!(
            s,
            "| {layer_cell} | [{}]({}/{}.md) | {} | {} | {} |",
            b.name,
            b.dir,
            b.name,
            text(&first_sentence(&b.summary)),
            if deps.is_empty() {
                "–".into()
            } else {
                deps.join(", ")
            },
            ctx.catalogue.of(&b.name).count()
        );
    }
    s.push_str("\n## Planned blocks\n\n");
    if ctx.planned.is_empty() {
        s.push_str("The KPI catalogue names no block beyond these. [Planned blocks](planned.md) lists a block once it does.\n");
    } else {
        let names: Vec<String> = ctx
            .planned
            .iter()
            .map(|p| format!("[{p}](planned.md#{p})"))
            .collect();
        let _ = writeln!(
            s,
            "The KPI catalogue already measures blocks the specification does not declare yet: {}. See [planned blocks](planned.md).",
            names.join(", ")
        );
    }
    s
}

pub fn planned_page(ctx: &Ctx) -> String {
    let mut s = String::new();
    front(
        &mut s,
        &[
            ("title", yaml("Planned blocks")),
            ("sidebar_label", yaml("Planned blocks")),
            ("slug", "/blocks/planned".into()),
            (
                "description",
                yaml("Blocks the KPI catalogue measures before the specification declares them."),
            ),
            (
                "lede",
                yaml(
                    "Blocks whose KPIs are defined before the specification declares their commands, events and views.",
                ),
            ),
            ("source", yaml("kpis/catalogue.yaml")),
            (
                "source_url",
                yaml(&format!("{SOURCE_BASE}kpis/catalogue.yaml")),
            ),
        ],
    );
    s.push_str("{/* Generated by agenticspec-docs from kpis/catalogue.yaml. Do not edit. */}\n\n");
    if ctx.planned.is_empty() {
        s.push_str("None: every block the KPI catalogue names is declared in the specification.\n");
        return s;
    }
    let _ = writeln!(
        s,
        "The [KPI catalogue](../kpis-catalogue.md) measures {} block{} the specification does not declare yet. \
Each gets its own page, with its entities, commands, events and views, once it is declared.\n",
        ctx.planned.len(),
        if ctx.planned.len() == 1 { "" } else { "s" }
    );
    for p in ctx.planned {
        let kpis: Vec<&Kpi> = ctx.catalogue.of(p).collect();
        let _ = writeln!(s, "## {p}\n");
        let _ = writeln!(
            s,
            "<BlockHeader name={} family={} planned counts={{{}}} />\n",
            attr(p),
            attr(crate::model::family(p)),
            json!({"kpis": kpis.len()})
        );
        kpi_sections(&mut s, &kpis, 3);
    }
    s
}

fn kpi_sections(s: &mut String, kpis: &[&Kpi], level: usize) {
    for kind in KINDS {
        let of: Vec<&Kpi> = kpis.iter().copied().filter(|k| k.kind == kind).collect();
        if of.is_empty() {
            continue;
        }
        let mut title = kind.to_string();
        title[..1].make_ascii_uppercase();
        let _ = writeln!(s, "{} {title}\n", "#".repeat(level));
        kpi_table(s, &of);
    }
}

/// The data the layer map component draws.
pub fn map_json(ctx: &Ctx, map: &Map) -> Value {
    let blocks: Vec<Value> = map
        .cards
        .iter()
        .map(|c| {
            let b = &ctx.blocks[c.index];
            json!({
                "name": b.name,
                "layer": b.layer,
                "family": b.family,
                "summary": first_sentence(&b.summary),
                "route": b.route(),
                "kpis": ctx.catalogue.of(&b.name).count(),
                "entities": ctx.count(b, "entities"),
                "commands": ctx.count(b, "commands"),
                "events": ctx.count(b, "events"),
                "views": ctx.count(b, "views"),
                "uses": ctx.depends_on(b).iter().map(|(d, _)| d.name.clone()).collect::<Vec<_>>(),
                "usedBy": ctx.used_by(b).iter().map(|(d, _)| d.name.clone()).collect::<Vec<_>>(),
                "x": c.x, "y": c.y, "w": c.w, "h": c.h,
            })
        })
        .collect();
    let edges: Vec<Value> = map
        .edges
        .iter()
        .map(|e| {
            json!({
                "from": ctx.blocks[e.from].name,
                "to": ctx.blocks[e.to].name,
                "count": e.count,
                "d": e.path,
            })
        })
        .collect();
    let rows: Vec<Value> = map
        .rows
        .iter()
        .map(|r| json!({"layer": r.layer, "name": r.name, "y": r.y, "h": r.h}))
        .collect();
    json!({
        "format": "agenticspec-docs-layer-map/1",
        "width": map.width,
        "height": map.height,
        "rows": rows,
        "blocks": blocks,
        "edges": edges,
    })
}

fn field_rows(s: &mut String, fields: &[Value]) {
    let meanings = fields.iter().any(|f| f["naming"]["summary"].is_string());
    if meanings {
        s.push_str("| field | type | meaning |\n|---|---|---|\n");
    } else {
        s.push_str("| field | type |\n|---|---|\n");
    }
    for f in fields {
        let name = code(f["name"].as_str().unwrap_or("?"));
        let ty = code(&type_ref(&f["type_ref"]));
        if meanings {
            let _ = writeln!(
                s,
                "| {name} | {ty} | {} |",
                text(f["naming"]["summary"].as_str().unwrap_or(""))
            );
        } else {
            let _ = writeln!(s, "| {name} | {ty} |");
        }
    }
    s.push('\n');
}

fn inline_fields(fields: &[Value]) -> String {
    if fields.is_empty() {
        return "–".into();
    }
    fields
        .iter()
        .map(|f| {
            format!(
                "{} {}",
                code(f["name"].as_str().unwrap_or("?")),
                text(&type_ref(&f["type_ref"]))
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn arr(v: &Value) -> Vec<Value> {
    v.as_array().cloned().unwrap_or_default()
}

fn lifecycle(s: &mut String, entity: &Value) {
    let lc = &entity["lifecycle"];
    if lc.is_null() {
        return;
    }
    let states: Vec<&str> = lc["states"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect();
    let transitions: Vec<Value> = arr(&lc["transitions"])
        .iter()
        .map(|t| json!({"name": t["name"], "from": t["from"], "to": t["to"]}))
        .collect();
    if transitions.is_empty() {
        if let Some(st) = lc["initial"].as_str() {
            let _ = writeln!(
                s,
                "Lifecycle: one state, `{st}`; a recorded {} does not change.\n",
                short(entity["name"].as_str().unwrap_or("?"))
            );
        }
        return;
    }
    let _ = writeln!(
        s,
        "<Lifecycle entity={} initial={} states={{{}}} terminal={{{}}} transitions={{{}}} />\n",
        attr(short(entity["name"].as_str().unwrap_or("?"))),
        attr(lc["initial"].as_str().unwrap_or("")),
        serde_json::to_string(&states).unwrap_or_default(),
        serde_json::to_string(&lc["terminal"].as_array().cloned().unwrap_or_default())
            .unwrap_or_default(),
        serde_json::to_string(&transitions).unwrap_or_default(),
    );
}

fn result(o: &Value, ctx: &Ctx) -> String {
    let mut parts = Vec::new();
    let subject = &o["subject"];
    if let Some(entity) = subject["entity"].as_str() {
        let e = short(entity);
        match subject["effect"].as_str() {
            Some("creates") => {
                let initial = ctx.ir["entities"][entity]["lifecycle"]["initial"].as_str();
                parts.push(match initial {
                    Some(st) => format!("creates a **{e}** in `{st}`"),
                    None => format!("creates a **{e}**"),
                });
            }
            Some("moves") => {
                let t = &subject["transition"];
                let from: Vec<&str> = t["from"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .filter_map(Value::as_str)
                    .collect();
                parts.push(format!(
                    "moves the **{e}** {} → `{}`",
                    from.iter()
                        .map(|f| format!("`{f}`"))
                        .collect::<Vec<_>>()
                        .join(", "),
                    t["to"].as_str().unwrap_or("?")
                ));
            }
            Some("updates") => parts.push(format!("updates the **{e}**")),
            Some("preserves") => parts.push(format!("leaves the **{e}** as it is")),
            _ => {}
        }
    }
    for a in arr(&o["affects"]) {
        let e = short(a["entity"].as_str().unwrap_or("?"));
        if let Some(to) = a["moves"]["to"].as_str() {
            parts.push(format!(
                "moves each **{e}** with {} to `{to}`",
                code(&predicate(&a["filter"]))
            ));
        } else {
            parts.push(format!(
                "updates each **{e}** with {}",
                code(&predicate(&a["filter"]))
            ));
        }
    }
    let emits: Vec<String> = arr(&o["emits"])
        .iter()
        .filter_map(Value::as_str)
        .map(|e| code(short(e)))
        .collect();
    if !emits.is_empty() {
        parts.push(format!("emits {}", emits.join(", ")));
    }
    if parts.is_empty() {
        "no change".into()
    } else {
        parts.join("; ")
    }
}

fn kpi_table(s: &mut String, kpis: &[&Kpi]) {
    s.push_str("| KPI | unit | better | gate | status |\n|---|---|---|---|---|\n");
    for k in kpis {
        let mut what = format!("{}<br/>{}", code(&k.id), text(&k.summary));
        if !k.how.is_empty() {
            let _ = write!(what, "<br/><small>How: {}</small>", text(&k.how));
        }
        if !k.modes.is_empty() {
            let modes: Vec<String> = k.modes.iter().map(|(m, d)| format!("{m}: {d}")).collect();
            let _ = write!(
                what,
                "<br/><small>By work mode: {}</small>",
                text(&modes.join(", "))
            );
        }
        let mut status = status_words(&k.status).to_string();
        if !k.source.is_empty() {
            let _ = write!(status, "<br/><small>source: {}</small>", text(&k.source));
        }
        let _ = writeln!(
            s,
            "| {what} | {} | {} | {} | {status} |",
            text(&k.unit),
            text(if k.direction.is_empty() {
                "–"
            } else {
                &k.direction
            }),
            if k.gate {
                "<span className=\"as-tag as-tag--gate\">gate</span>"
            } else {
                "–"
            },
        );
    }
    s.push('\n');
}

pub fn page(ctx: &Ctx, b: &Block) -> String {
    let ir = ctx.ir;
    let mut s = String::new();
    front(
        &mut s,
        &[
            ("title", yaml(&b.name)),
            ("sidebar_label", yaml(&b.name)),
            ("slug", format!("/{}/{}/{}", b.section, b.dir, b.page)),
            ("description", yaml(&first_sentence(&b.summary))),
            (
                "kicker",
                yaml(&if b.in_pack() {
                    format!("Pack · {}", b.dir)
                } else {
                    format!("Layer {} · {}", b.layer, b.layer_name())
                }),
            ),
            ("source", yaml(&b.file)),
            ("source_url", yaml(&format!("{SOURCE_BASE}{}", b.file))),
        ],
    );
    if b.in_pack() {
        s.push_str(&GENERATED_NOTE.replace(
            "the specification in blocks/",
            &format!("the specification in packs/{}/", b.dir),
        ));
    } else {
        s.push_str(GENERATED_NOTE);
    }
    let entities = members(ir, &b.domain, "entities");
    let commands = members(ir, &b.domain, "commands");
    let events = members(ir, &b.domain, "events");
    let views = members(ir, &b.domain, "views");
    let actors = members(ir, &b.domain, "actors");
    let kpis: Vec<&Kpi> = ctx.catalogue.of(&b.name).collect();
    let place = if b.in_pack() {
        format!("pack={}", attr(&b.dir))
    } else {
        format!("layer={{{}}} layerName={}", b.layer, attr(b.layer_name()))
    };
    let _ = writeln!(
        s,
        "<BlockHeader name={} family={} {place} counts={{{}}} />\n",
        attr(&b.name),
        attr(b.family),
        json!({
            "entities": entities.len(),
            "commands": commands.len(),
            "events": events.len(),
            "views": views.len(),
            "refusals": ctx.refusals(b),
            "kpis": kpis.len(),
        })
    );
    let _ = writeln!(s, "{}\n", text(&b.summary));

    s.push_str("## Depends on\n\n");
    let deps = ctx.depends_on(b);
    if deps.is_empty() {
        s.push_str("Nothing: this block is the foundation.\n\n");
    } else {
        for (d, n) in deps {
            let _ = writeln!(
                s,
                "- [{}]({}) · {} · {} reference{}",
                d.name,
                rel(b, d),
                d.place(),
                n,
                if n == 1 { "" } else { "s" }
            );
        }
        s.push('\n');
    }
    s.push_str("## Used by\n\n");
    let users = ctx.used_by(b);
    if users.is_empty() {
        s.push_str("No block depends on this one.\n\n");
    } else {
        for (d, n) in users {
            let _ = writeln!(
                s,
                "- [{}]({}) · {} · {} reference{}",
                d.name,
                rel(b, d),
                d.place(),
                n,
                if n == 1 { "" } else { "s" }
            );
        }
        s.push('\n');
    }

    if !entities.is_empty() {
        s.push_str("## Entities\n\n");
        for e in &entities {
            let name = short(e["name"].as_str().unwrap_or("?"));
            let _ = writeln!(s, "### {name}\n");
            if let Some(sum) = e["naming"]["summary"].as_str() {
                let _ = writeln!(s, "{}\n", text(sum));
            }
            if let Some(id) = e["identity"]["name"].as_str() {
                let _ = writeln!(
                    s,
                    "Identified by {} ({}).\n",
                    code(id),
                    code(&type_ref(&e["identity"]["type_ref"]))
                );
            }
            let fields = arr(&e["fields"]);
            if !fields.is_empty() {
                field_rows(&mut s, &fields);
            }
            let relations = arr(&e["relations"]);
            if !relations.is_empty() {
                s.push_str("Relations:\n\n");
                for r in relations {
                    let target = r["target"].as_str().unwrap_or("?");
                    let target_text = match ctx.block(&crate::model::entity_domain(ir, target)) {
                        Some(tb) if tb.domain != b.domain => {
                            format!("**{}** of [{}]({})", short(target), tb.name, rel(b, tb))
                        }
                        _ => format!("**{}**", short(target)),
                    };
                    let _ = writeln!(
                        s,
                        "- {} {} {target_text} ({}, by {})",
                        code(r["name"].as_str().unwrap_or("?")),
                        r["kind"].as_str().unwrap_or("references"),
                        r["cardinality"].as_str().unwrap_or("one"),
                        code(r["via"].as_str().unwrap_or("?"))
                    );
                }
                s.push('\n');
            }
            let invariants: Vec<String> = arr(&e["invariants"])
                .iter()
                .map(|i| code(&predicate(i)))
                .collect();
            if !invariants.is_empty() {
                let _ = writeln!(s, "Always holds: {}.\n", invariants.join(", "));
            }
            lifecycle(&mut s, e);
        }
    }

    if !commands.is_empty() {
        s.push_str("## Commands\n\n");
        for c in &commands {
            let qname = c["name"].as_str().unwrap_or("?");
            let name = short(qname);
            let _ = writeln!(s, "### {name}\n");
            let display = c["naming"]["display"].as_str();
            let summary = c["naming"]["summary"].as_str();
            match (display, summary) {
                (Some(d), Some(sum)) => {
                    let _ = writeln!(s, "**{}.** {}\n", text(d), text(sum));
                }
                (Some(d), None) => {
                    let _ = writeln!(s, "**{}.**\n", text(d));
                }
                (None, Some(sum)) => {
                    let _ = writeln!(s, "{}\n", text(sum));
                }
                _ => {}
            }
            let callers: Vec<String> = actors
                .iter()
                .filter(|a| {
                    a["may"]
                        .as_array()
                        .into_iter()
                        .flatten()
                        .any(|m| m.as_str() == Some(qname))
                })
                .map(|a| {
                    text(
                        a["naming"]["display"]
                            .as_str()
                            .unwrap_or(short(a["name"].as_str().unwrap_or("?"))),
                    )
                })
                .collect();
            if !callers.is_empty() {
                let _ = writeln!(s, "Called by: {}.\n", callers.join(", "));
            }
            let input = arr(&c["input"]);
            if input.is_empty() {
                s.push_str("No input.\n\n");
            } else {
                field_rows(&mut s, &input);
            }
            let outcomes = arr(&c["outcomes"]);
            let subject = outcomes
                .iter()
                .find_map(|o| o["subject"]["entity"].as_str())
                .or_else(|| entities.first().and_then(|e| e["name"].as_str()));
            s.push_str("| outcome | when | result |\n|---|---|---|\n");
            for o in &outcomes {
                let oname = o["name"].as_str().unwrap_or("?");
                let when = condition(&o["condition"], subject);
                if let Some(err) = o["error"].as_str() {
                    let why = ir["errors"][err]["summary"].as_str().unwrap_or("");
                    let _ = writeln!(
                        s,
                        "| {} <span className=\"as-tag as-tag--refused\">refused</span> | {when} | {}{} |",
                        code(oname),
                        code(short(err)),
                        if why.is_empty() {
                            String::new()
                        } else {
                            format!(": {}", text(why))
                        }
                    );
                } else {
                    let _ = writeln!(s, "| {} | {when} | {} |", code(oname), result(o, ctx));
                }
            }
            s.push('\n');
        }
    }

    if !events.is_empty() {
        s.push_str("## Events\n\n| event | fields | emitted by |\n|---|---|---|\n");
        for e in &events {
            let qname = e["name"].as_str().unwrap_or("?");
            let by: Vec<String> = commands
                .iter()
                .filter(|c| {
                    c["outcomes"].as_array().into_iter().flatten().any(|o| {
                        o["emits"]
                            .as_array()
                            .into_iter()
                            .flatten()
                            .any(|x| x.as_str() == Some(qname))
                    })
                })
                .map(|c| code(short(c["name"].as_str().unwrap_or("?"))))
                .collect();
            let mut what = code(short(qname));
            if let Some(sum) = e["naming"]["summary"].as_str() {
                let _ = write!(what, "<br/>{}", text(sum));
            }
            let _ = writeln!(
                s,
                "| {what} | {} | {} |",
                inline_fields(&arr(&e["fields"])),
                if by.is_empty() {
                    "–".into()
                } else {
                    by.join(", ")
                }
            );
        }
        s.push('\n');
    }

    if !views.is_empty() {
        s.push_str("## Views\n\n| view | rows | fields |\n|---|---|---|\n");
        for v in &views {
            let mut what = code(short(v["name"].as_str().unwrap_or("?")));
            if let Some(d) = v["naming"]["display"].as_str() {
                let _ = write!(what, "<br/>{}", text(d));
            }
            let mut rows = match v["source"].as_str() {
                Some(src) => format!("each **{}**", short(src)),
                None => "–".into(),
            };
            if !v["filter"].is_null() {
                let _ = write!(rows, " with {}", code(&predicate(&v["filter"])));
            }
            let params = arr(&v["params"]);
            if !params.is_empty() {
                let _ = write!(rows, "<br/>asked with {}", inline_fields(&params));
            }
            let _ = writeln!(
                s,
                "| {what} | {rows} | {} |",
                inline_fields(&arr(&v["fields"]))
            );
        }
        s.push('\n');
    }

    let types: Vec<(&String, &Value)> = ir["domains"][&b.domain]["types"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .filter(|t| !t.ends_with(".State"))
        .filter_map(|t| ir["types"].as_object().and_then(|o| o.get_key_value(t)))
        .collect();
    if !types.is_empty() {
        s.push_str("## Types\n\n| type | is | values or fields |\n|---|---|---|\n");
        for (name, t) in types {
            let body = &t["body"];
            let (is, detail) = match body["kind"].as_str() {
                Some("enum") => (
                    "one of".to_string(),
                    arr(&body["variants"])
                        .iter()
                        .filter_map(Value::as_str)
                        .map(code)
                        .collect::<Vec<_>>()
                        .join(", "),
                ),
                Some("newtype") => (
                    "an identifier or value".to_string(),
                    code(&type_ref(&body["of"])),
                ),
                Some("struct") => ("a record".to_string(), inline_fields(&arr(&body["fields"]))),
                Some("union") => (
                    "exactly one of".to_string(),
                    body["variants"]
                        .as_object()
                        .map(|m| {
                            m.iter()
                                .map(|(k, v)| format!("{} {}", code(k), text(&type_ref(v))))
                                .collect::<Vec<_>>()
                                .join(", ")
                        })
                        .unwrap_or_default(),
                ),
                Some(other) => (other.to_string(), String::new()),
                None => ("?".into(), String::new()),
            };
            let mut what = code(short(name));
            if let Some(sum) = t["naming"]["summary"].as_str() {
                let _ = write!(what, "<br/>{}", text(sum));
            }
            let _ = writeln!(s, "| {what} | {is} | {detail} |");
        }
        s.push('\n');
    }

    s.push_str("## KPIs\n\n");
    if kpis.is_empty() {
        s.push_str("No KPI of this block is in the catalogue yet.\n");
    } else {
        let from = if b.in_pack() {
            format!(
                "the pack's catalogue, [packs/{0}/kpis.yaml]({SOURCE_BASE}packs/{0}/kpis.yaml)",
                b.dir
            )
        } else {
            "the [KPI catalogue](../../kpis-catalogue.md)".to_string()
        };
        let _ = writeln!(
            s,
            "{} KPI{} from {from}. A gate must be zero for a variant of an architecture to count.\n",
            kpis.len(),
            if kpis.len() == 1 { "" } else { "s" }
        );
        kpi_sections(&mut s, &kpis, 3);
    }
    s
}

pub fn kpi_json(ctx: &Ctx) -> Value {
    let rows: Vec<Value> = ctx
        .catalogue
        .kpis
        .iter()
        .map(|k| {
            let b = ctx.blocks.iter().find(|b| b.name == k.block);
            json!({
                "id": k.id,
                "block": k.block,
                "layer": b.map(|b| b.layer),
                "family": crate::model::family(&k.block),
                "planned": b.is_none(),
                "route": b.map_or(format!("/docs/blocks/planned#{}", k.block), |b| format!("{}#kpis", b.route())),
                "kind": k.kind,
                "unit": k.unit,
                "summary": k.summary,
                "how": k.how,
                "direction": k.direction,
                "modes": k.modes.iter().map(|(m, d)| json!({"mode": m, "direction": d})).collect::<Vec<_>>(),
                "gate": k.gate,
                "reads": k.reads,
                "status": k.status,
                "source": k.source,
            })
        })
        .collect();
    json!({"format": "agenticspec-docs-kpis/1", "kpis": rows})
}

pub fn catalogue_page(ctx: &Ctx) -> String {
    let mut s = String::new();
    front(
        &mut s,
        &[
            ("title", yaml("KPI catalogue")),
            ("sidebar_label", yaml("KPI catalogue")),
            ("slug", "/kpis-catalogue".into()),
            (
                "description",
                yaml(
                    "Every KPI of every building block, with its kind, unit, direction, gate and status.",
                ),
            ),
            (
                "lede",
                yaml(
                    "Every KPI of every building block: what it measures, which way is better, whether it is a gate, and whether it is computed today.",
                ),
            ),
            ("source", yaml("kpis/catalogue.yaml")),
            (
                "source_url",
                yaml(&format!("{SOURCE_BASE}kpis/catalogue.yaml")),
            ),
            ("hide_table_of_contents", "true".into()),
        ],
    );
    s.push_str("{/* Generated by agenticspec-docs from kpis/catalogue.yaml. Do not edit. */}\n\n");
    let n = ctx.catalogue.kpis.len();
    let gates = ctx.catalogue.kpis.iter().filter(|k| k.gate).count();
    let _ = writeln!(
        s,
        "{n} KPI{} over {} blocks; {gates} of them gates. A KPI has one of three kinds: \
**correctness** is a check that passes or fails, **completeness** is the share of what was promised that exists, \
**quality** is a number with a direction. A gate must be zero for a variant of an architecture to count. \
The status says where a KPI is computed: by `agenticspec kpi` on observed sessions today, by the simulator, by both, or not yet.\n",
        if n == 1 { "" } else { "s" },
        ctx.blocks
            .iter()
            .filter(|b| ctx.catalogue.of(&b.name).next().is_some())
            .count(),
    );
    s.push_str(
        "Filter by block, kind, status or gate, search by name, and sort by any column.\n\n",
    );
    s.push_str("<KpiCatalogue />\n\n");
    s.push_str("## By block\n\n");
    for b in ctx.blocks {
        let ids: Vec<String> = ctx.catalogue.of(&b.name).map(|k| code(&k.id)).collect();
        if ids.is_empty() {
            continue;
        }
        let _ = writeln!(
            s,
            "- [{}](blocks/{}/{}.md#kpis): {}",
            b.name,
            b.dir,
            b.name,
            ids.join(", ")
        );
    }
    for p in ctx.planned {
        let ids: Vec<String> = ctx.catalogue.of(p).map(|k| code(&k.id)).collect();
        let _ = writeln!(
            s,
            "- [{p}](blocks/planned.md#{p}) (planned): {}",
            ids.join(", ")
        );
    }
    s
}

/// The generated parts of the sidebar. `packs` and `fields` are the items of the categories Packs
/// and Fields: one category per pack with its block pages, and the pages of each field.
pub fn sidebar_json(
    blocks: &[Block],
    architectures: &[String],
    catalog: &[String],
    packs: Vec<Value>,
    fields: Vec<Value>,
) -> Value {
    let mut layers: Vec<Value> = Vec::new();
    let mut by: BTreeMap<u32, Vec<&Block>> = BTreeMap::new();
    for b in blocks {
        by.entry(b.layer).or_default().push(b);
    }
    for (layer, bs) in by {
        layers.push(json!({
            "type": "category",
            "label": format!("{layer} · {}", bs[0].layer_name()),
            "collapsed": true,
            "items": bs.iter().map(|b| b.doc_id()).collect::<Vec<_>>(),
        }));
    }
    layers.push(json!("docs/blocks/planned"));
    json!({
        "blocks": layers,
        "architectures": architectures.iter().map(|a| format!("docs/architectures/{a}")).collect::<Vec<_>>(),
        "catalog": catalog.iter().map(|c| format!("docs/catalog/{c}")).collect::<Vec<_>>(),
        "packs": packs,
        "fields": fields,
    })
}
