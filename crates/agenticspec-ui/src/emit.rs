struct PageOut<'a> {
    kit: BTreeSet<&'static str>,
    rt: BTreeSet<&'static str>,
    field_defs: bool,
    script: String,
    page: &'a PageModel,
}

fn field_def(f: &FieldModel) -> String {
    let mut parts = vec![
        format!("field: {}", ts_str(&f.field)),
        format!("label: {}", ts_str(&f.label)),
        format!("as: {}", ts_str(f.as_.word())),
    ];
    if let Some(l) = &f.labels {
        parts.push(format!(
            "labels: {{ {} }}",
            l.iter()
                .map(|(k, v)| format!("{}: {}", ts_str(k), ts_str(v)))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    if let Some(t) = &f.tones {
        parts.push(format!(
            "tones: {{ {} }}",
            t.iter()
                .map(|(k, v)| format!("{}: {}", ts_str(k), ts_str(v.word())))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    if let Some(t) = f.tone {
        parts.push(format!("tone: {}", ts_str(t.word())));
    }
    format!("{{ {} }}", parts.join(", "))
}

fn indent(text: &str, by: usize) -> String {
    let pad = " ".repeat(by);
    text.lines()
        .map(|l| {
            if l.is_empty() {
                String::new()
            } else {
                format!("{pad}{l}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

impl PageOut<'_> {
    fn kit(&mut self, name: &'static str) -> &'static str {
        self.kit.insert(name);
        name
    }

    fn fields_const(&mut self, name: &str, fields: &[FieldModel]) -> String {
        self.field_defs = true;
        let var = format!("fields_{name}");
        let _ = writeln!(self.script, "const {var}: FieldDef[] = [");
        for f in fields {
            let _ = writeln!(self.script, "  {},", field_def(f));
        }
        self.script.push_str("];\n");
        var
    }

    fn read_decl(&mut self, r: &ReadUse) {
        self.rt.insert("useRead");
        let params: Vec<String> = r
            .params
            .iter()
            .map(|(k, v)| format!("{}: {v}", prop(k)))
            .collect();
        let live = match &r.live {
            Some((channel, on)) => format!(
                ", {{ channel: {}, on: [{}] }}",
                ts_str(channel),
                on.iter().map(|e| ts_str(e)).collect::<Vec<_>>().join(", ")
            ),
            None => String::new(),
        };
        let _ = writeln!(
            self.script,
            "const {} = useRead({}, () => ({{{}}}){live});",
            r.var,
            ts_str(&r.view),
            if params.is_empty() {
                String::new()
            } else {
                format!(" {} ", params.join(", "))
            }
        );
    }

    /// An action as template: a link, a copy button or a button that sends a command.
    fn action(&mut self, a: &ActionModel, in_row: bool) -> String {
        match &a.kind {
            ActionKind::Navigate { page, params } => {
                self.kit("KitLink");
                let ps: Vec<String> = params
                    .iter()
                    .map(|(k, v)| format!("{}: {v}", prop(k)))
                    .collect();
                format!(
                    "<KitLink :href=\"router.href({}, {{ {} }})\">{}</KitLink>\n",
                    ts_str(page),
                    ps.join(", "),
                    html(&a.label)
                )
            }
            ActionKind::Copy(expr) => {
                self.kit("KitCopy");
                self.rt.insert("text");
                format!(
                    "<KitCopy :value=\"text({expr})\" label=\"{}\" />\n",
                    html(&a.label)
                )
            }
            ActionKind::Does {
                command,
                var,
                input,
            } => {
                self.kit("KitButton");
                self.rt.insert("useCommand");
                let fields: Vec<String> = input
                    .iter()
                    .map(|(k, v)| format!("{}: {v}", prop(k)))
                    .collect();
                let object = if fields.is_empty() {
                    "{}".to_string()
                } else {
                    format!("{{ {} }}", fields.join(", "))
                };
                if in_row {
                    let nulls: Vec<String> = input
                        .iter()
                        .map(|(k, _)| format!("{}: null", prop(k)))
                        .collect();
                    let _ = writeln!(
                        self.script,
                        "const {var} = useCommand({}, () => ({}));",
                        ts_str(command),
                        if nulls.is_empty() {
                            "{}".to_string()
                        } else {
                            format!("{{ {} }}", nulls.join(", "))
                        }
                    );
                    format!(
                        "<KitButton tone=\"secondary\" size=\"sm\" :busy=\"{var}.busy\" @click=\"{var}.run({object})\">{}</KitButton>\n",
                        html(&a.label)
                    )
                } else {
                    let _ = writeln!(
                        self.script,
                        "const {var} = useCommand({}, () => ({object}));",
                        ts_str(command)
                    );
                    format!(
                        "<KitButton tone=\"primary\" :busy=\"{var}.busy\" :disabled=\"{var}.blocked\" @click=\"{var}.run()\">{}</KitButton>\n",
                        html(&a.label)
                    )
                }
            }
        }
    }

    fn choice(&mut self, c: &ChoiceModel) -> String {
        self.kit("KitSelect");
        let opts = match &c.read {
            Some(r) => {
                self.read_decl(r);
                self.rt.insert("options");
                format!(
                    "options({}.rows, {}, {})",
                    r.var,
                    ts_str(&c.value),
                    ts_str(&c.shows)
                )
            }
            None => format!(
                "[{}]",
                c.options
                    .iter()
                    .map(|(v, l)| format!("{{ value: {}, label: {} }}", scalar(v), ts_str(l)))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        };
        let state = ts_str(&c.binds);
        format!(
            "<KitSelect label=\"{}\"{} :options=\"{opts}\" :model-value=\"page.state[{state}]\" @update:model-value=\"page.state[{state}] = $event\" />\n",
            html(&c.label),
            c.placeholder
                .as_ref()
                .map(|p| format!(" placeholder=\"{}\"", html(p)))
                .unwrap_or_default()
        )
    }

    fn search(&mut self, state: &str, label: &str, placeholder: Option<&str>) -> String {
        self.kit("KitSearch");
        self.rt.insert("text");
        let st = ts_str(state);
        format!(
            "<KitSearch label=\"{}\"{} :model-value=\"text(page.state[{st}])\" @update:model-value=\"page.state[{st}] = $event\" />\n",
            html(label),
            placeholder
                .map(|p| format!(" placeholder=\"{}\"", html(p)))
                .unwrap_or_default()
        )
    }

    fn bar(&mut self, s: &SectionModel) -> String {
        let SectionKind::FilterBar {
            choices,
            search,
            actions,
        } = &s.kind
        else {
            return String::new();
        };
        self.kit("KitToolbar");
        let mut inner = String::new();
        for c in choices {
            inner.push_str(&self.choice(c));
        }
        if let Some((state, placeholder)) = search {
            inner.push_str(&self.search(state, "Search", placeholder.as_deref()));
        }
        for a in actions {
            inner.push_str(&self.action(a, false));
        }
        format!(
            "<KitToolbar label=\"{}\">\n{}</KitToolbar>\n",
            html(s.title.as_deref().unwrap_or("Filters")),
            indent(&inner, 2)
        )
    }

    fn row_actions(&mut self, actions: &[ActionModel]) -> String {
        if actions.is_empty() {
            return String::new();
        }
        let mut inner = String::new();
        for a in actions {
            inner.push_str(&self.action(a, true));
        }
        format!(
            "<template #actions=\"{{ row }}\">\n{}</template>\n",
            indent(&inner, 2)
        )
    }

    fn section(&mut self, s: &SectionModel, fill: bool) -> String {
        self.kit("KitPanel");
        if let Some(r) = &s.read {
            self.read_decl(r);
        }
        let mut attrs = format!(" name=\"{}\"", html(&s.name));
        if let Some(t) = &s.title {
            let _ = write!(attrs, " title=\"{}\" collapsible", html(t));
            if s.collapsed {
                attrs.push_str(" :collapsed=\"true\"");
            }
        }
        let host = matches!(s.kind, SectionKind::Host { .. });
        if fill {
            attrs.push_str(" fill");
        }
        if host && s.title.is_none() {
            attrs.push_str(" bare");
        }
        if let (Some(r), false) = (&s.read, host) {
            let _ = write!(
                attrs,
                " :state=\"{}.state\" :error=\"{}.error\"",
                r.var, r.var
            );
            if let Some((title, message)) = &s.empty {
                if let Some(t) = title {
                    let _ = write!(attrs, " empty-title=\"{}\"", html(t));
                }
                let _ = write!(attrs, " empty-message=\"{}\"", html(message));
            }
            if let Some(m) = &s.failed {
                let _ = write!(attrs, " failed-message=\"{}\"", html(m));
            }
            let _ = write!(attrs, " @retry=\"{}.reload()\"", r.var);
        }
        let body = match &s.kind {
            SectionKind::Host { host } => match &s.read {
                Some(r) => format!("<component :is=\"hosts.{host}\" :read=\"{}\" />\n", r.var),
                None => format!("<component :is=\"hosts.{host}\" />\n"),
            },
            SectionKind::Collection {
                columns,
                list,
                row_actions,
                search,
            } => {
                let r = s.read.as_ref();
                let rows = match (r, r.and_then(|r| r.filter.as_ref())) {
                    (Some(r), Some((field, state))) => {
                        self.rt.insert("contains");
                        format!(
                            "{}.rows.filter((row) => contains(row[{}], page.state[{}]))",
                            r.var,
                            ts_str(field),
                            ts_str(state)
                        )
                    }
                    (Some(r), None) => format!("{}.rows", r.var),
                    (None, _) => "[]".into(),
                };
                let mut out = String::new();
                if let Some(state) = search {
                    let label = format!(
                        "Find in {}",
                        s.title.as_deref().unwrap_or(&s.name).to_lowercase()
                    );
                    out.push_str(&self.search(state, &label, None));
                }
                let var = self.fields_const(&s.var, columns);
                let tag = self.kit(if *list { "KitList" } else { "KitTable" });
                let key = r.and_then(|r| r.key.clone()).unwrap_or_else(|| "id".into());
                let empty = s
                    .empty
                    .as_ref()
                    .map(|(_, m)| format!(" empty-message=\"{}\"", html(m)))
                    .unwrap_or_default();
                let actions = self.row_actions(row_actions);
                if actions.is_empty() {
                    let _ = writeln!(
                        out,
                        "<{tag} label=\"{}\" :columns=\"{var}\" :rows=\"{rows}\" row-key=\"{}\"{empty} />",
                        html(s.title.as_deref().unwrap_or(&s.name)),
                        html(&key)
                    );
                } else {
                    let _ = write!(
                        out,
                        "<{tag} label=\"{}\" :columns=\"{var}\" :rows=\"{rows}\" row-key=\"{}\"{empty}>\n{}</{tag}>\n",
                        html(s.title.as_deref().unwrap_or(&s.name)),
                        html(&key),
                        indent(&actions, 2)
                    );
                }
                out
            }
            SectionKind::Record { fields, actions } => {
                self.kit("KitRecord");
                let var = self.fields_const(&s.var, fields);
                let row = s
                    .read
                    .as_ref()
                    .map(|r| format!("{}.row", r.var))
                    .unwrap_or_else(|| "null".into());
                let acts = self.row_actions(actions);
                if acts.is_empty() {
                    format!("<KitRecord :fields=\"{var}\" :row=\"{row}\" />\n")
                } else {
                    format!(
                        "<KitRecord :fields=\"{var}\" :row=\"{row}\">\n{}</KitRecord>\n",
                        indent(&acts, 2)
                    )
                }
            }
            SectionKind::Form {
                command,
                fields,
                submit,
                result,
            } => self.form(s, command, fields, submit, result.as_ref()),
            SectionKind::FilterBar { .. } => self.bar(s),
        };
        format!("<KitPanel{attrs}>\n{}</KitPanel>\n", indent(&body, 2))
    }

    fn form(
        &mut self,
        s: &SectionModel,
        command: &str,
        fields: &[crate::check::FormField],
        submit: &str,
        result: Option<&(String, Vec<FieldModel>)>,
    ) -> String {
        self.kit("KitForm");
        self.rt.insert("useForm");
        let var = format!("f_{}", s.var);
        let initial: Vec<String> = fields
            .iter()
            .map(|f| {
                let v = match f.input {
                    FormInput::Toggle => "false",
                    FormInput::Number => "null",
                    _ => "''",
                };
                format!("{}: {v}", prop(&f.field))
            })
            .collect();
        let context: Vec<String> = self
            .page
            .params
            .iter()
            .map(|p| format!("{}: page.params[{}]", prop(p), ts_str(p)))
            .collect();
        let _ = writeln!(
            self.script,
            "const {var} = useForm({}, {{{}}}, () => ({{{}}}));",
            ts_str(command),
            if initial.is_empty() {
                String::new()
            } else {
                format!(" {} ", initial.join(", "))
            },
            if context.is_empty() {
                String::new()
            } else {
                format!(" {} ", context.join(", "))
            }
        );
        let mut inner = String::new();
        for f in fields {
            let key = ts_str(&f.field);
            let id = format!("{}-{}", s.name, f.field).replace(['_', '.'], "-");
            let model = |cast: &str| {
                format!(
                    ":model-value=\"{cast}({var}.draft[{key}])\" @update:model-value=\"{var}.draft[{key}] = $event\""
                )
            };
            match &f.input {
                FormInput::Toggle => {
                    self.kit("KitSwitch");
                    self.rt.insert("flag");
                    let _ = writeln!(
                        inner,
                        "<KitSwitch label=\"{}\" {} />",
                        html(&f.label),
                        model("flag")
                    );
                }
                FormInput::Host(host) => {
                    self.kit("KitField");
                    self.rt.insert("text");
                    let _ = writeln!(
                        inner,
                        "<KitField label=\"{}\" for=\"{id}\">\n  <component :is=\"hosts.{host}\" id=\"{id}\" label=\"{}\" {} />\n</KitField>",
                        html(&f.label),
                        html(&f.label),
                        model("text")
                    );
                }
                FormInput::Text | FormInput::Number => {
                    self.kit("KitField");
                    self.kit("KitTextInput");
                    self.rt.insert("text");
                    let kind = if matches!(f.input, FormInput::Number) {
                        " type=\"number\""
                    } else {
                        ""
                    };
                    let _ = writeln!(
                        inner,
                        "<KitField label=\"{}\" for=\"{id}\">\n  <KitTextInput id=\"{id}\"{kind} {} />\n</KitField>",
                        html(&f.label),
                        model("text")
                    );
                }
            }
        }
        if let Some((name, rfields)) = result {
            self.kit("KitRecord");
            let fvar = self.fields_const(&format!("{}_{}", s.var, ident(name)), rfields);
            let _ = write!(
                inner,
                "<template #result>\n  <KitRecord v-if=\"{var}.answer\" :fields=\"{fvar}\" :row=\"{var}.answer\" :tone=\"{var}.refused ? 'danger' : 'neutral'\" />\n</template>\n"
            );
        }
        format!(
            "<KitForm submit-label=\"{}\" :busy=\"{var}.busy\" @submit=\"{var}.submit()\">\n{}</KitForm>\n",
            html(submit),
            indent(&inner, 2)
        )
    }

    fn column(&mut self, sections: &[SectionModel], fill_one_host: bool) -> String {
        if let ([only], true) = (sections, fill_one_host)
            && matches!(only.kind, SectionKind::Host { .. })
        {
            return self.section(only, true);
        }
        self.kit("KitStack");
        let mut inner = String::new();
        for s in sections {
            inner.push_str(&self.section(s, false));
        }
        format!("<KitStack>\n{}</KitStack>\n", indent(&inner, 2))
    }
}

fn page_vue(app: &App, page: &PageModel) -> String {
    let mut out = PageOut {
        kit: BTreeSet::new(),
        rt: BTreeSet::new(),
        field_defs: false,
        script: String::new(),
        page,
    };
    out.kit("KitShell");
    let bar = page.bar.as_ref().map(|b| out.bar(b));
    let body = if page.side.is_empty() {
        out.column(&page.main, true)
    } else {
        out.kit("KitSplit");
        let main = out.column(&page.main, true);
        let side = out.column(&page.side, false);
        format!(
            "<KitSplit>\n  <template #main>\n{}  </template>\n  <template #side>\n{}  </template>\n</KitSplit>\n",
            indent(&main, 4),
            indent(&side, 4)
        )
    };
    let title = match &page.title_from {
        Some((var, field)) => {
            out.rt.insert("text");
            format!(
                ":page-title=\"text({var}.row?.[{}]) || {}\"",
                ts_str(field),
                ts_str(&page.title)
            )
        }
        None => format!("page-title=\"{}\"", html(&page.title)),
    };
    let mut tpl = format!(
        "<KitShell :title=\"shell.title\" {title} :theme=\"shell.theme\" :themes=\"shell.themes\" :toasts=\"shell.toasts\" @update:theme=\"shell.setTheme\" @dismiss=\"shell.dismiss\">\n"
    );
    if let Some(b) = bar {
        let _ = write!(tpl, "  <template #bar>\n{}  </template>\n", indent(&b, 4));
    }
    tpl.push_str(&indent(&body, 2));
    tpl.push_str("</KitShell>\n");

    // Declarations, each only when the template or script uses it.
    out.rt.insert("useShell");
    let uses = |needle: &str| tpl.contains(needle) || out.script.contains(needle);
    let mut decls = String::from("const shell = useShell();\n");
    if uses("router.") {
        out.rt.insert("useRouter");
        decls.push_str("const router = useRouter();\n");
    }
    if uses("hosts.") {
        out.rt.insert("useHosts");
        decls.push_str("const hosts = useHosts();\n");
    }
    if uses("page.") {
        out.rt.insert("usePage");
        let states: Vec<String> = page
            .state
            .iter()
            .map(|(n, st)| {
                format!(
                    " {}: {{ store: {}, initial: {} }}",
                    prop(n),
                    ts_str(store_word(st.store)),
                    scalar(&st.initial)
                )
            })
            .collect();
        let _ = writeln!(
            decls,
            "const page = usePage({{ params: [{}], state: {{{}}} }});",
            page.params
                .iter()
                .map(|p| ts_str(p))
                .collect::<Vec<_>>()
                .join(", "),
            if states.is_empty() {
                String::new()
            } else {
                format!("{} ", states.join(","))
            }
        );
    }

    let mut s = head_vue(app);
    s.push_str("<script setup lang=\"ts\">\n");
    let mut kit: Vec<String> = out.kit.iter().map(|k| k.to_string()).collect();
    if out.field_defs {
        kit.push("type FieldDef".into());
    }
    let _ = writeln!(s, "import {{ {} }} from '@kit';", kit.join(", "));
    let _ = writeln!(
        s,
        "import {{ {} }} from '../runtime';\n",
        out.rt.iter().copied().collect::<Vec<_>>().join(", ")
    );
    s.push_str(&decls);
    s.push_str(&out.script);
    s.push_str("</script>\n\n<template>\n");
    s.push_str(&indent(&tpl, 2));
    s.push_str("</template>\n");
    s
}

pub fn emit(app: &App) -> Files {
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    files.insert("runtime.ts".into(), RUNTIME.to_string());
    files.insert("client.ts".into(), client(app));
    files.insert("hosts.ts".into(), hosts(app));
    files.insert("router.ts".into(), router(app));
    files.insert("app.ts".into(), app_ts(app));
    files.insert("App.vue".into(), app_vue(app));
    for p in &app.pages {
        debug_assert_eq!(p.component, component_name(&p.name));
        files.insert(format!("pages/{}.vue", p.component), page_vue(app, p));
    }
    files
}
