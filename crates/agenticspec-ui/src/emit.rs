fn head_ts(app: &App) -> String {
    format!(
        "// Generated by agenticspec ui generate from the ess-ui/1 document of `{}`. Never edit: change the\n// document and generate again.\n",
        app.name
    )
}

fn head_vue(app: &App) -> String {
    format!(
        "<!-- Generated by agenticspec ui generate from the ess-ui/1 document of `{}`. Never edit: change\n     the document and generate again. -->\n",
        app.name
    )
}

/// Text in a template, safe from markup and interpolation.
fn html(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('{', "&#123;")
        .replace('}', "&#125;")
}

/// `studio.draft.Drafts` → `StudioDraftDrafts`.
fn type_name(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(|c: char| !c.is_ascii_alphanumeric()) {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.push(c.to_ascii_uppercase());
            out.extend(cs);
        }
    }
    out
}

fn object_type(fields: &BTreeSet<String>, optional: bool) -> String {
    if fields.is_empty() {
        return "Record<string, never>".into();
    }
    let q = if optional { "?" } else { "" };
    format!(
        "{{ {} }}",
        fields
            .iter()
            .map(|f| format!("{}{q}: Value", prop(f)))
            .collect::<Vec<_>>()
            .join("; ")
    )
}

/// A property name, quoted when it is no identifier.
fn prop(name: &str) -> String {
    if !name.is_empty()
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !name.starts_with(|c: char| c.is_ascii_digit())
    {
        name.to_string()
    } else {
        ts_str(name)
    }
}

fn client(app: &App) -> String {
    let mut s = head_ts(app);
    s.push_str(
        "//\n// The typed client of the reads, commands and channels the document names. A read is\n// `GET /api/views/<view>?<params>`, answered `{\"rows\": [...]}`; a command is\n// `POST /api/commands/<command>` with its input as JSON, answered `{\"row\": ...}` (a refusal the\n// command declares is status 422 with its row); a channel is `GET /api/channels/<channel>`, a\n// stream of server-sent events named by the event they carry.\n\n",
    );
    s.push_str("export type Value = string | number | boolean | null | Value[] | { [key: string]: Value };\nexport type Row = Record<string, Value>;\n\n");
    for (view, sig) in &app.reads {
        let _ = writeln!(
            s,
            "/** The rows of `{view}`{}, by the fields the document reads. */\nexport type {}Row = {};\n",
            if sig.placeholder {
                " (a placeholder until the model holds the view)"
            } else {
                ""
            },
            type_name(view),
            object_type(&sig.fields, true)
        );
    }
    s.push_str("/** Every read of the document: the parameters it takes and its rows. */\nexport interface Reads {\n");
    for (view, sig) in &app.reads {
        let _ = writeln!(
            s,
            "  {}: {{ params: {}; row: {}Row }};",
            ts_str(view),
            object_type(&sig.params, false),
            type_name(view)
        );
    }
    s.push_str("}\n\n");
    for (cmd, sig) in &app.commands {
        if !sig.answer.is_empty() {
            let _ = writeln!(
                s,
                "/** The answer of `{cmd}`, by the fields the document shows. */\nexport type {}Answer = {};\n",
                type_name(cmd),
                object_type(&sig.answer, true)
            );
        }
    }
    s.push_str("/** Every command of the document and the input it sends. */\nexport interface Commands {\n");
    for (cmd, sig) in &app.commands {
        let _ = writeln!(
            s,
            "  {}: {{ input: {} }};",
            ts_str(cmd),
            object_type(&sig.input, false)
        );
    }
    s.push_str("}\n\n/** Every channel of the document and the events it carries. */\nexport interface Channels {\n");
    for (name, c) in &app.channels {
        let events = if c.events.is_empty() {
            c.view
                .as_ref()
                .map(|v| ts_str(v))
                .unwrap_or_else(|| "never".into())
        } else {
            c.events
                .iter()
                .map(|e| ts_str(e))
                .collect::<Vec<_>>()
                .join(" | ")
        };
        let _ = writeln!(
            s,
            "  {}: {{ events: {events}; per: {} }};",
            prop(name),
            c.per
                .as_ref()
                .map(|p| ts_str(p))
                .unwrap_or_else(|| "null".into())
        );
    }
    s.push_str("}\n\nexport type ChannelName = keyof Channels;\n\n");
    let list = |names: Vec<&String>| {
        names
            .iter()
            .map(|n| ts_str(n))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ = writeln!(
        s,
        "export const READS = [{}] as const;",
        list(app.reads.keys().collect())
    );
    let _ = writeln!(
        s,
        "export const COMMANDS = [{}] as const;",
        list(app.commands.keys().collect())
    );
    let _ = writeln!(
        s,
        "export const CHANNELS = [{}] as const;\n",
        list(app.channels.keys().collect())
    );
    s.push_str("const CHANNEL_EVENTS: Record<ChannelName, readonly string[]> = {");
    let entries: Vec<String> = app
        .channels
        .iter()
        .map(|(n, c)| {
            let evs: Vec<String> = c
                .events
                .iter()
                .chain(c.view.iter())
                .map(|e| ts_str(e))
                .collect();
            format!(" {}: [{}]", prop(n), evs.join(", "))
        })
        .collect();
    if entries.is_empty() {
        s.push_str("};\n\n");
    } else {
        let _ = writeln!(s, "{} }};\n", entries.join(","));
    }
    s.push_str(CLIENT_BODY);
    s
}

const CLIENT_BODY: &str = r#"/** What a command answered: carried out (`ok`) or refused as the command declares, with its row. */
export interface CommandAnswer {
  ok: boolean;
  row: Row | null;
}

/** A read or command the server refused outright, by its error name. */
export class Refused extends Error {
  readonly status: number;
  readonly error: string;
  constructor(status: number, error: string, message: string) {
    super(message ? `${error}: ${message}` : error);
    this.status = status;
    this.error = error;
  }
}

export interface Client {
  read<V extends keyof Reads>(view: V, params: Reads[V]['params']): Promise<Row[]>;
  command<C extends keyof Commands>(command: C, input: Commands[C]['input']): Promise<CommandAnswer>;
  subscribe(channel: ChannelName, params: Record<string, Value>, onEvent: (event: string, data: Value) => void): () => void;
}

function query(params: object): string {
  const q = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) {
    if (v !== null && v !== undefined) q.set(k, String(v));
  }
  const s = q.toString();
  return s ? `?${s}` : '';
}

async function body(r: Response): Promise<Record<string, Value>> {
  const t = await r.text();
  try {
    return JSON.parse(t) as Record<string, Value>;
  } catch {
    throw new Refused(r.status, 'InvalidAnswer', t.slice(0, 200));
  }
}

export function createClient(base = '', fetcher: typeof fetch = (input, init) => fetch(input, init)): Client {
  return {
    async read(view, params) {
      const r = await fetcher(`${base}/api/views/${view}${query(params)}`);
      const b = await body(r);
      if (!r.ok) throw new Refused(r.status, String(b.error ?? r.status), String(b.message ?? ''));
      return (Array.isArray(b.rows) ? b.rows : []) as Row[];
    },
    async command(command, input) {
      const r = await fetcher(`${base}/api/commands/${command}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(input),
      });
      const b = await body(r);
      if (r.ok) return { ok: true, row: (b.row ?? null) as Row | null };
      if (r.status === 422 && b.row && typeof b.row === 'object') return { ok: false, row: b.row as Row };
      throw new Refused(r.status, String(b.error ?? r.status), String(b.message ?? ''));
    },
    subscribe(channel, params, onEvent) {
      const source = new EventSource(`${base}/api/channels/${channel}${query(params)}`);
      const handler = (e: MessageEvent<string>) => {
        let data: Value;
        try {
          data = JSON.parse(e.data) as Value;
        } catch {
          data = e.data;
        }
        onEvent(e.type, data);
      };
      for (const ev of (CHANNEL_EVENTS as Record<string, readonly string[]>)[channel] ?? []) source.addEventListener(ev, handler as EventListener);
      source.onmessage = handler;
      return () => source.close();
    },
  };
}
"#;

fn hosts(app: &App) -> String {
    let mut s = head_ts(app);
    s.push_str("//\n// The host slots of the document: the components the host registers by these names, and the\n// props each is given. ESS does not draw them; each says why the generator cannot.\n\n");
    let field = app.hosts.values().any(|h| h.field);
    let reads = app.hosts.values().any(|h| h.reads.is_some());
    let _ = writeln!(s, "import type {{ Component }} from 'vue';");
    if reads {
        let _ = writeln!(s, "import type {{ ReadState }} from './runtime';");
    }
    let _ = field;
    s.push('\n');
    for (name, h) in &app.hosts {
        let _ = writeln!(
            s,
            "/**\n * `{}`, standing in for `{}`: {}\n */",
            h.at,
            h.stands_in_for,
            h.reason.split_whitespace().collect::<Vec<_>>().join(" ")
        );
        if h.field {
            let _ = writeln!(
                s,
                "export interface {name}Props {{\n  /** The id its input carries, which the field's label names. */\n  id: string;\n  label: string;\n  modelValue: string;\n}}\n"
            );
        } else {
            match &h.reads {
                Some(view) => {
                    let _ = writeln!(
                        s,
                        "export interface {name}Props {{\n  read: ReadState<{}>;\n}}\n",
                        ts_str(view)
                    );
                }
                None => {
                    let _ = writeln!(s, "export type {name}Props = Record<string, never>;\n");
                }
            }
        }
    }
    s.push_str("/** The components the host registers, one per host slot. */\nexport interface HostComponents {\n");
    for name in app.hosts.keys() {
        let _ = writeln!(s, "  {name}: Component;");
    }
    s.push_str("}\n\n");
    let _ = writeln!(
        s,
        "export const HOSTS = [{}] as const;",
        app.hosts
            .keys()
            .map(|n| ts_str(n))
            .collect::<Vec<_>>()
            .join(", ")
    );
    s
}

fn router(app: &App) -> String {
    let mut s = head_ts(app);
    s.push_str("//\n// One route per page: `#/` is the home page, every other page `#/<name, its dots as slashes>/<params>`.\n\n");
    s.push_str("import type { RouteDef } from './runtime';\n");
    for p in &app.pages {
        let _ = writeln!(
            s,
            "import {} from './pages/{}.vue';",
            p.component, p.component
        );
    }
    s.push_str("\nexport const routes: RouteDef[] = [\n");
    for p in &app.pages {
        let _ = writeln!(
            s,
            "  {{ name: {}, segments: [{}], params: [{}], component: {} }},",
            ts_str(&p.name),
            p.segments
                .iter()
                .map(|x| ts_str(x))
                .collect::<Vec<_>>()
                .join(", "),
            p.params
                .iter()
                .map(|x| ts_str(x))
                .collect::<Vec<_>>()
                .join(", "),
            p.component
        );
    }
    s.push_str("];\n");
    s
}

fn store_word(s: Store) -> &'static str {
    match s {
        Store::Memory | Store::SessionStorage => "memory",
        Store::Url => "url",
        Store::LocalStorage => "local_storage",
    }
}

fn scalar(v: &Value) -> String {
    match v {
        Value::Array(_) | Value::Object(_) => ts_str(&v.to_string()),
        other => ts_value(other),
    }
}

fn app_ts(app: &App) -> String {
    let mut s = head_ts(app);
    s.push_str("//\n// The app: its client, its routes and the host's components and hooks. The host calls\n// `createGeneratedApp({ hosts, hooks })` and mounts what it returns.\n\n");
    s.push_str("import { createApp, type Component } from 'vue';\nimport App from './App.vue';\nimport { createClient } from './client';\nimport type { HostComponents } from './hosts';\nimport { install, type CommandHooks } from './runtime';\nimport { routes } from './router';\n\n");
    s.push_str("export interface GeneratedAppOptions {\n  hosts: HostComponents;\n  hooks?: CommandHooks;\n  /** The origin of the server, empty for the one that served the app. */\n  base?: string;\n}\n\n");
    s.push_str("export function createGeneratedApp(options: GeneratedAppOptions) {\n  const app = createApp(App);\n  install(app, {\n");
    let _ = writeln!(s, "    app: {},", ts_str(&app.name));
    let _ = writeln!(s, "    title: {},", ts_str(&app.title));
    let _ = writeln!(s, "    home: {},", ts_str(&app.home));
    s.push_str("    routes,\n    client: createClient(options.base ?? ''),\n    hosts: options.hosts as unknown as Record<string, Component>,\n    hooks: options.hooks ?? {},\n");
    s.push_str("    shell: {");
    let defs: Vec<String> = app
        .shell_state
        .iter()
        .map(|(n, st)| {
            format!(
                " {}: {{ store: {}, initial: {} }}",
                prop(n),
                ts_str(store_word(st.store)),
                scalar(&st.initial)
            )
        })
        .collect();
    if defs.is_empty() {
        s.push_str("},\n");
    } else {
        let _ = writeln!(s, "{} }},", defs.join(","));
    }
    match &app.theme {
        Some(t) => {
            let _ = writeln!(
                s,
                "    theme: {{ initial: {}, themes: [{}], state: {} }},",
                ts_str(&t.default),
                t.themes
                    .iter()
                    .map(|x| ts_str(x))
                    .collect::<Vec<_>>()
                    .join(", "),
                t.state
                    .as_ref()
                    .map(|x| ts_str(x))
                    .unwrap_or_else(|| "null".into())
            );
        }
        None => s.push_str("    theme: null,\n"),
    }
    s.push_str("  });\n  return app;\n}\n");
    s
}

fn app_vue(app: &App) -> String {
    let mut s = head_vue(app);
    s.push_str("<script setup lang=\"ts\">\nimport { useApp } from './runtime';\n\nconst app = useApp();\n</script>\n\n<template>\n  <component :is=\"app.page\" :key=\"app.pageKey\" />\n</template>\n");
    s
}

